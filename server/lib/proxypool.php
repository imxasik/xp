/** cURL-এর জন্য প্রক্সি স্ট্রিং সাজানো */
function pool_curl_proxy(string $u): string
{
    if (str_starts_with($u, 'socks5://'))  return 'socks5h://' . substr($u, 9);
    if (str_starts_with($u, 'socks4://'))  return 'socks4a://' . substr($u, 9);
    return $u;
}

/**
 * একসাথে অনেকগুলো প্রক্সি যাচাই — আসল সোর্স URL-এ ঢুকে দেখে।
 * @return array{tested:int,working:int,results:array}
 */
function pool_test(?array $subset = null, int $parallel = 0, int $timeout = 0): array
{
    if (!function_exists('curl_multi_init')) {
        return ['tested' => 0, 'working' => 0, 'results' => [], 'error' => 'curl_multi নেই'];
    }
    $parallel = $parallel ?: (int)pcfg('pool_test_parallel', 20);
    $timeout  = $timeout  ?: (int)pcfg('pool_test_timeout', 12);
    $target   = rtrim((string)cfg('source_url'), '/') . '/';

    $d    = pool_load();
    $urls = $subset ?? array_keys($d['list'] ?? []);
    $urls = array_values(array_unique($urls));

    $results = []; $working = 0;

    foreach (array_chunk($urls, max(1, $parallel)) as $chunk) {
        $mh = curl_multi_init();
        $hs = [];
        foreach ($chunk as $u) {
            $ch = curl_init($target);
            curl_setopt_array($ch, [
                CURLOPT_RETURNTRANSFER => true,
                CURLOPT_FOLLOWLOCATION => true,
                CURLOPT_TIMEOUT        => $timeout,
                CURLOPT_CONNECTTIMEOUT => min(8, $timeout),
                CURLOPT_SSL_VERIFYPEER => false,
                CURLOPT_SSL_VERIFYHOST => 0,
                CURLOPT_PROXY          => pool_curl_proxy($u),
                CURLOPT_HTTPPROXYTUNNEL => stripos($target, 'https://') === 0,
                CURLOPT_USERAGENT      => 'Mozilla/5.0 (Linux; Android 13) BAFWX-Mirror/1.3',
            ]);
            curl_multi_add_handle($mh, $ch);
            $hs[$u] = $ch;
        }
        $running = null;
        do {
            curl_multi_exec($mh, $running);
            if ($running) curl_multi_select($mh, 0.5);
        } while ($running > 0);

        foreach ($hs as $u => $ch) {
            $body = curl_multi_getcontent($ch);
            $code = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
            $ms   = (int)(curl_getinfo($ch, CURLINFO_TOTAL_TIME) * 1000);
            $ok   = $code === 200 && is_string($body) && strlen($body) > 100;
            $results[$u] = ['ok' => $ok, 'http' => $code, 'ms' => $ms, 'bytes' => strlen((string)$body)];
            if ($ok) $working++;

            $e = $d['list'][$u] ?? ['score' => 0, 'ok' => 0, 'fail' => 0, 'ms' => 0, 'last_ok' => 0, 'src' => '?'];
            if ($ok) {
                $e['ok']++; $e['fail'] = 0; $e['score'] = min(100, (int)$e['score'] + 12);
                $e['last_ok'] = time(); $e['ms'] = $ms;
            } else {
                $e['fail']++; $e['score'] = max(-40, (int)$e['score'] - 14);
            }
            $d['list'][$u] = $e;

            curl_multi_remove_handle($mh, $ch);
            curl_close($ch);
        }
        curl_multi_close($mh);
    }

    $d['tested'] = time();
    pool_save($d);
    uasort($results, fn($a, $b) => ($b['ok'] <=> $a['ok']) ?: ($a['ms'] <=> $b['ms']));
    return ['tested' => count($results), 'working' => $working, 'results' => $results];
}
