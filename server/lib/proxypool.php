        ',4095;1333249,511;513,1023;102928385,4095;147457,4095;3424257,511;1516033,1023;493569,511;1025,511;1' .
        '72042241,1023;415745,1023;5812225,1023;7169,2047;8435713,2047;27366401,1023;86017,4095;160769,1023;6' .
        '565889,511;2291713,511';

    $r = []; $prev = 0;
    foreach (explode(';', $data) as $pair) {
        [$d, $len] = array_map('intval', explode(',', $pair));
        $start = $prev + $d;
        $end   = $start + $len;
        $r[]   = [$start, $end];
        $prev  = $end;
    }
    return $r;
}

function is_bd_ip(string $ip): bool
{
    $n = ip2long($ip);
    if ($n === false) return false;
    $n = $n < 0 ? $n + 4294967296 : $n;

    $r = bd_ranges();
    $lo = 0; $hi = count($r) - 1;
    while ($lo <= $hi) {                       // বাইনারি সার্চ
        $mid = ($lo + $hi) >> 1;
        if ($n < $r[$mid][0])      $hi = $mid - 1;
        elseif ($n > $r[$mid][1])  $lo = $mid + 1;
        else                       return true;
    }
    return false;
}

/* ══════════════════════════════════════════════════════════════
   স্টোরেজ
   ══════════════════════════════════════════════════════════════ */

function pool_load(): array
{
    $d = store_read('proxies.json', []);
    if (empty($d['list']) || !is_array($d['list'])) {
        $d = ['list' => [], 'updated' => 0, 'tested' => 0, 'current' => ''];
        foreach (pool_seed() as $u => $ms) {
            // মাপা গতি রেখে দিই — pool_best() দ্রুততমগুলো আগে চেষ্টা করবে
            $d['list'][$u] = ['score' => 5, 'ok' => 0, 'fail' => 0,
                              'ms' => (int)$ms, 'last_ok' => 0, 'src' => 'seed'];
        }
        store_write('proxies.json', $d);
    }
    return $d;
}

function pool_save(array $d): bool
{
    // খুব বড় হতে দেব না
    if (count($d['list'] ?? []) > 400) {
        uasort($d['list'], fn($a, $b) => ($b['score'] ?? 0) <=> ($a['score'] ?? 0));
        $d['list'] = array_slice($d['list'], 0, 300, true);
    }
    return store_write('proxies.json', $d);
}

/** সফল/ব্যর্থ রিপোর্ট → স্কোর হালনাগাদ */
function pool_mark(string $url, bool $ok, int $ms = 0): void
{
    $d = pool_load();
    $e = $d['list'][$url] ?? ['score' => 0, 'ok' => 0, 'fail' => 0, 'ms' => 0, 'last_ok' => 0, 'src' => '?'];
    if ($ok) {
        $e['ok']++;
        $e['fail']    = 0;
        $e['score']   = min(100, (int)$e['score'] + 12);
        $e['last_ok'] = time();
        $e['ms']      = $e['ms'] > 0 ? (int)round($e['ms'] * 0.6 + $ms * 0.4) : $ms;
        $d['current'] = $url;
    } else {
        $e['fail']++;
        $e['score'] = max(-40, (int)$e['score'] - 14);
        if ($d['current'] === $url) $d['current'] = '';
    }
    $d['list'][$url] = $e;

    // একেবারে মৃতগুলো ঝেড়ে ফেলি
    foreach ($d['list'] as $k => $v) {
        if (($v['score'] ?? 0) <= -40 && ($v['fail'] ?? 0) >= 4 && ($v['ok'] ?? 0) === 0) {
            unset($d['list'][$k]);
        }
    }
    pool_save($d);
}

/**
 * সেরা প্রক্সিগুলো ক্রম অনুযায়ী।
 * অগ্রাধিকার: সর্বশেষ সফল > স্কোর > গতি
 */
function pool_best(int $limit = 8): array
{
    $d    = pool_load();
    $list = $d['list'] ?? [];
    $now  = time();

    // cURL না থাকলে SOCKS প্রক্সি ব্যবহার করা যায় না (stream wrapper শুধু HTTP বোঝে)।
    // তাই ওগুলো বাদ দিই, নইলে প্রতিটা চেষ্টাই বৃথা যাবে।
    if (!function_exists('curl_init')) {
        $list = array_filter($list, fn($k) => str_starts_with($k, 'http'), ARRAY_FILTER_USE_KEY);
    }

    // হোস্ট যদি শুধু কিছু পোর্টে বাইরে যেতে দেয়, বাকিগুলো চেষ্টা করাই বৃথা
    $allow = array_map('intval', (array)pcfg('pool_ports', []));
    if (!empty($allow)) {
        $list = array_filter($list, function ($k) use ($allow) {
            $port = (int)parse_url($k, PHP_URL_PORT);
            return $port > 0 && in_array($port, $allow, true);
        }, ARRAY_FILTER_USE_KEY);
    }

    $rank = [];
    foreach ($list as $url => $e) {
        $score = (float)($e['score'] ?? 0);
        $lastOk = (int)($e['last_ok'] ?? 0);
        if ($lastOk > 0) {
            $age = $now - $lastOk;
            if ($age < 1800)      $score += 40;   // শেষ ৩০ মিনিটে কাজ করেছে
            elseif ($age < 21600) $score += 20;   // শেষ ৬ ঘণ্টায়
        }
        $ms = (int)($e['ms'] ?? 0);
        if ($ms > 0) $score += max(-10, 10 - $ms / 1000); // দ্রুত হলে বোনাস
        $score -= (int)($e['fail'] ?? 0) * 6;
        $rank[$url] = $score;
    }
    arsort($rank);

    // গতবার যেটা কাজ করেছিল সেটা সবার আগে (sticky)
    $out = array_keys($rank);
    $cur = (string)($d['current'] ?? '');
    if ($cur !== '' && isset($list[$cur])) {
        $out = array_values(array_diff($out, [$cur]));
        array_unshift($out, $cur);
    }
    return array_slice($out, 0, max(1, $limit));
}

/* ══════════════════════════════════════════════════════════════
   তালিকা রিফ্রেশ
   ══════════════════════════════════════════════════════════════ */

function pool_parse_text(string $body): array
{
    $out = [];
    // "socks5://1.2.3.4:1080" বা খালি "1.2.3.4:1080"
    if (preg_match_all('#(?:(socks5|socks4|https?)://)?(\d{1,3}(?:\.\d{1,3}){3}):(\d{2,5})#i', $body, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) {
            $proto = strtolower($x[1] ?: 'http');
            if ($proto === 'https') $proto = 'http';
            $out[] = $proto . '://' . $x[2] . ':' . $x[3];
        }
    }
    return $out;
}

/**
 * HTML পাতা থেকে প্রক্সি বের করা।
 * এই সাইটগুলো IP আর পোর্ট আলাদা ঘরে রাখে, তাই সাধারণ "ip:port" খোঁজা কাজ করে না।
 * ⚠️ সাইটের ডিজাইন বদলালে এগুলো কাজ করা বন্ধ করতে পারে — তখনও বাকি ২৮টি উৎস চলবে।
 */
function pool_parse_html(string $body): array
{
    $out = [];

    // freeproxy.world →  <td ...>IP</td> <td><a ...>PORT</a></td>
    if (preg_match_all('#<td[^>]*>\s*(\d{1,3}(?:\.\d{1,3}){3})\s*</td>\s*<td[^>]*>\s*<a[^>]*>\s*(\d{2,5})\s*</a>#i',
                       $body, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) $out[] = 'http://' . $x[1] . ':' . $x[2];
    }

    // proxyhub.me →  <span class="ip-text" ...>IP</span> … <span class="port-text">PORT</span>
    if (preg_match_all('#class="ip-text"[^>]*>\s*(\d{1,3}(?:\.\d{1,3}){3})\s*</span>.*?class="port-text"\s*>\s*(\d{2,5})#is',
                       $body, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) $out[] = 'http://' . $x[1] . ':' . $x[2];
    }

    return $out;
}

/**
 * JSON উৎস থেকে প্রক্সি বের করা — একাধিক সাইটের ফরম্যাট সামলায়:
 *   geonode        : {"data":[{ip, port, protocols, country}]}
 *   proxyfreeonly  : [{ip, port, protocols, country}]
 *   proxy5.net     : {"results":[{ip_address, port, protocols, country_code}]}
 */
function pool_parse_json(string $body): array
{
    $j = json_decode($body, true);

    // ⚠️ কিছু সাইট (যেমন proxy5.net) ২.৪ MB-এর পর JSON কেটে দেয়, ফলে
    //    json_decode() ব্যর্থ হয়। তখন নিয়মভিত্তিকভাবে রেকর্ড তুলে নিই —
    //    যতটুকু এসেছে ততটুকু কাজে লাগে।
    if (!is_array($j)) return pool_parse_json_partial($body);

    $rows = $j['data'] ?? $j['results'] ?? $j['proxies'] ?? $j['list']
         ?? (array_is_list($j) ? $j : []);
    if (!is_array($rows) || empty($rows)) return pool_parse_json_partial($body);

    $out = [];
    foreach ($rows as $p) {
        if (!is_array($p)) continue;

        // দেশ — যে চাবিতেই থাকুক
        $cc = strtoupper((string)($p['country_code'] ?? $p['country'] ?? $p['countryCode'] ?? ''));
        if ($cc !== '' && $cc !== 'BD' && stripos($cc, 'BANGLADESH') === false) continue;

        $ip = (string)($p['ip'] ?? $p['ip_address'] ?? $p['address'] ?? $p['host'] ?? '');
        $pt = (int)($p['port'] ?? 0);
        if ($ip === '' || $pt < 1 || $pt > 65535) continue;

        $protos = $p['protocols'] ?? $p['protocol'] ?? $p['type'] ?? ['http'];
        foreach ((array)$protos as $pr) {
            $pr = strtolower(trim((string)$pr));
            if ($pr === 'https' || $pr === '') $pr = 'http';
            if (!in_array($pr, ['http', 'socks4', 'socks5'], true)) continue;
            $out[] = $pr . '://' . $ip . ':' . $pt;
        }
    }
    return $out;
}

/** কাটা/ভাঙা JSON থেকে যতটুকু পারা যায় তুলে নেওয়া */
function pool_parse_json_partial(string $body): array
{
    $re = '#"(?:ip|ip_address|address|host)"\s*:\s*"(\d{1,3}(?:\.\d{1,3}){3})"\s*,'
        . '\s*"port"\s*:\s*"?(\d{2,5})"?(.{0,1500}?)'
        . '(?="(?:ip|ip_address|address|host)"\s*:|\z)#s';
    if (!preg_match_all($re, $body, $m, PREG_SET_ORDER)) return [];

    $out = [];
    foreach ($m as $x) {
        $tail = $x[3];
        // দেশ উল্লেখ থাকলে বাংলাদেশ কিনা দেখি; না থাকলে IP-রেঞ্জই শেষ কথা
        if (preg_match('#"country(?:_code)?"\s*:\s*"([^"]+)"#i', $tail, $c)) {
            $v = strtoupper($c[1]);
            if ($v !== 'BD' && stripos($v, 'BANGLADESH') === false) continue;
        }
        $pr = 'http';
        if (stripos($tail, 'socks5') !== false)      $pr = 'socks5';
        elseif (stripos($tail, 'socks4') !== false)  $pr = 'socks4';
        $out[] = $pr . '://' . $x[1] . ':' . (int)$x[2];
    }
    return $out;
}

/** পুরোনো নাম — পুরোনো কোড ভেঙে না যায় তাই রাখা */
function pool_parse_geonode(string $body): array { return pool_parse_json($body); }

/** পাবলিক উৎস থেকে নতুন প্রক্সি আনা (সরাসরি, প্রক্সি ছাড়াই) */
function pool_refresh(bool $force = false): array
{
    $d = pool_load();
    $hrs = (int)pcfg('pool_refresh_hours', 6);
    if (!$force && $hrs > 0 && (time() - (int)($d['updated'] ?? 0)) < $hrs * 3600) {
        return ['skipped' => true, 'total' => count($d['list'] ?? [])];
    }

    $added = 0; $seen = 0; $srcOk = 0; $skipped = 0; $notes = [];
    $allowPorts = array_map('intval', (array)pcfg('pool_ports', []));
    foreach (pool_sources() as $src) {
        $body = pool_plain_get($src, 25);
        if ($body === null || $body === '') { $notes[] = 'fail:' . parse_url($src, PHP_URL_HOST); continue; }
        $srcOk++;
        $trimmed = ltrim($body);
        if (str_contains($src, 'geonode') || str_starts_with($trimmed, '[') || str_starts_with($trimmed, '{')) {
            $items = pool_parse_json($body);              // JSON
        } elseif (stripos($trimmed, '<html') !== false || str_contains($trimmed, '<td')) {
            $items = pool_parse_html($body);             // HTML টেবিল
        } else {
            $items = pool_parse_text($body);             // সাধারণ তালিকা
        }
        foreach ($items as $u) {
            $seen++;

            // ⭐ শুধু বাংলাদেশি IP রাখি। সাধারণ তালিকায় ১.৫ লাখ প্রক্সি থাকে,
            //    তার ~১% বাংলাদেশি। না ছেঁকে নিলে পুল আবর্জনায় ভরে যাবে।
            $host = (string)parse_url($u, PHP_URL_HOST);
            if ($host === '' || !is_bd_ip($host)) { $skipped++; continue; }

            // হোস্ট যদি শুধু কিছু পোর্টে যেতে দেয়, বাকিগুলো রেখে লাভ নেই
            if (!empty($allowPorts) && !in_array((int)parse_url($u, PHP_URL_PORT), $allowPorts, true)) {
                $skipped++; continue;
            }

            if (!isset($d['list'][$u])) {
                $d['list'][$u] = ['score' => 0, 'ok' => 0, 'fail' => 0, 'ms' => 0, 'last_ok' => 0,
                                  'src' => (string)parse_url($src, PHP_URL_HOST)];
                $added++;
            }
        }
    }
    $d['updated'] = time();
    pool_save($d);
    return ['skipped' => false, 'sources_ok' => $srcOk, 'seen' => $seen,
            'non_bd' => $skipped, 'added' => $added,
            'total' => count($d['list']), 'notes' => $notes];
}

/** প্রক্সি ছাড়া সাধারণ GET (তালিকা নামানোর জন্য) */
function pool_plain_get(string $url, int $timeout = 20): ?string
{
    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_FOLLOWLOCATION => true,
            CURLOPT_TIMEOUT        => $timeout,
            CURLOPT_CONNECTTIMEOUT => 12,
            CURLOPT_SSL_VERIFYPEER => false,
            CURLOPT_SSL_VERIFYHOST => 0,
            // কিছু সাইট বট-UA দেখলে ব্লক করে
            CURLOPT_USERAGENT      => 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) '
                                    . 'AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36',
            CURLOPT_HTTPHEADER     => ['Accept-Language: en-US,en;q=0.9'],
        ]);
        $b = curl_exec($ch);
        curl_close($ch);
        return is_string($b) ? $b : null;
    }
    $ctx = stream_context_create(['http' => ['timeout' => $timeout],
                                  'ssl' => ['verify_peer' => false, 'verify_peer_name' => false]]);
    $b = @file_get_contents($url, false, $ctx);
    return is_string($b) ? $b : null;
}

